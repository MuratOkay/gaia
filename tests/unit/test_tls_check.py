"""The directory's TLS check (D76): the handshake the sign-in will make, explained.

Real TLS servers on 127.0.0.1 (LDAPS, and StartTLS answered by hand) with certificates made
here — among them the case found on the owner's host: a Samba AD provisioned again, whose new
self-signed CA has the *same name* as the one in ``acme-ca.pem`` but another key, so OpenSSL
reports "certificate signature failure" (its leaf certificate carries no authority key id,
as Samba's do not)."""

from __future__ import annotations

import datetime as dt
import ipaddress
import socket
import ssl
import threading
from pathlib import Path

import pytest
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

from gaia.auth.ldap import LdapDirectory, LdapSettings
from gaia.auth.tls import check_tls, describe_tls_error, load_ca, resolve_ca_file

NOW = dt.datetime.now(dt.UTC)
CA_NAME = x509.Name([
    x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Samba Administration"),
    x509.NameAttribute(NameOID.ORGANIZATIONAL_UNIT_NAME,
                       "Samba - temporary autogenerated CA certificate"),
    x509.NameAttribute(NameOID.COMMON_NAME, "DC1.acme.test")])


def _key():
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


def _ca(name=CA_NAME):
    key = _key()
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name)
            .public_key(key.public_key()).serial_number(x509.random_serial_number())
            .not_valid_before(NOW - dt.timedelta(days=1))
            .not_valid_after(NOW + dt.timedelta(days=700))
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    return cert, key


def _leaf(ca, ca_key, names=("localhost",), days=(-1, 700)):
    key = _key()
    alt = [x509.DNSName(n) for n in names] + [x509.IPAddress(ipaddress.ip_address("127.0.0.1"))]
    cert = (x509.CertificateBuilder()
            .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, names[0])]))
            .issuer_name(ca.subject).public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(NOW + dt.timedelta(days=days[0]))
            .not_valid_after(NOW + dt.timedelta(days=days[1]))
            .add_extension(x509.SubjectAlternativeName(alt), critical=False)
            .sign(ca_key, hashes.SHA256()))  # no authority key id, like Samba's
    return cert, key


def _pem(cert) -> str:
    return cert.public_bytes(serialization.Encoding.PEM).decode()


class Server:
    """A TLS server for one certificate; ``starttls`` answers the LDAP StartTLS request
    first; ``plain`` never speaks TLS."""

    def __init__(self, tmp: Path, cert, key, *, starttls=False, plain=False, refuse=False):
        self.sock = socket.socket()
        self.sock.bind(("127.0.0.1", 0))
        self.sock.listen(8)
        self.port = self.sock.getsockname()[1]
        self.starttls, self.plain, self.refuse = starttls, plain, refuse
        self.ctx = None
        if cert is not None:
            cf, kf = tmp / f"c{self.port}.pem", tmp / f"k{self.port}.pem"
            cf.write_text(_pem(cert))
            kf.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                                             serialization.PrivateFormat.PKCS8,
                                             serialization.NoEncryption()))
            self.ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
            self.ctx.load_cert_chain(cf, kf)
        threading.Thread(target=self._serve, daemon=True).start()

    def _serve(self):
        while True:
            try:
                conn, _ = self.sock.accept()
            except OSError:
                return
            threading.Thread(target=self._one, args=(conn,), daemon=True).start()

    def _one(self, conn):
        try:
            conn.settimeout(5)
            if self.plain:
                conn.recv(1024)
                conn.sendall(b"HTTP/1.0 400 nope\r\n\r\n")
                return
            if self.starttls:
                conn.recv(1024)  # the ExtendedRequest
                code = b"\x35" if self.refuse else b"\x00"  # 53 unwillingToPerform
                body = b"\x0a\x01" + code + b"\x04\x00\x04\x00"
                op = b"\x78" + bytes([len(body)]) + body
                msg = b"\x02\x01\x01" + op
                conn.sendall(b"\x30" + bytes([len(msg)]) + msg)
                if self.refuse:
                    return
            with self.ctx.wrap_socket(conn, server_side=True) as tls:
                tls.recv(1)
        except Exception:  # noqa: BLE001, S110 - the client hangs up on purpose
            pass
        finally:
            conn.close()

    def close(self):
        self.sock.close()


@pytest.fixture(scope="module")
def pki():
    ca1, k1 = _ca()
    ca2, k2 = _ca()  # provisioned again: same name, new key
    other, ko = _ca(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Another CA")]))
    return {"ca1": (ca1, k1), "ca2": (ca2, k2), "other": (other, ko)}


def _ca_file(tmp: Path, *certs) -> str:
    path = tmp / "ca.pem"
    path.write_text("".join(_pem(c) for c in certs))
    return str(path)


def test_a_verified_handshake_names_the_certificate_and_the_ca(tmp_path, pki):
    leaf, key = _leaf(*pki["ca1"])
    srv = Server(tmp_path, leaf, key)
    ca = load_ca(_ca_file(tmp_path, pki["ca1"][0]))
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert r.ok, r.detail
    assert "LDAPS to localhost" in r.detail and "verified against" in r.detail
    assert "DC1.acme.test" in r.detail and "SHA-256" in r.detail
    srv.close()


def test_a_ca_created_anew_under_the_same_name_is_explained(tmp_path, pki):
    leaf, key = _leaf(*pki["ca2"])  # the directory's new CA signed it
    srv = Server(tmp_path, leaf, key)
    ca = load_ca(_ca_file(tmp_path, pki["ca1"][0]))  # Gaia still trusts the old one
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and r.verify_code == 7  # "certificate signature failure"
    assert "created anew" in r.detail and "samba-ad-test.sh ca" in r.detail
    assert r.server is not None and r.server["issuer"] == pki["ca2"][0].subject.rfc4514_string()
    # copying the current CA over the old one is the fix
    ca = load_ca(_ca_file(tmp_path, pki["ca2"][0]))
    assert check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca).ok
    srv.close()


def test_another_issuer_a_hostname_mismatch_and_an_expired_certificate(tmp_path, pki):
    ca = load_ca(_ca_file(tmp_path, pki["ca1"][0]))
    leaf, key = _leaf(*pki["other"])
    srv = Server(tmp_path, leaf, key)
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and r.verify_code in (20, 21) and "Another CA" in r.detail
    srv.close()

    leaf, key = _leaf(*pki["ca1"], names=("dc1.acme.test",))
    srv = Server(tmp_path, leaf, key)
    # the certificate carries 127.0.0.1 as well: reach it by a name it does not carry
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and "dc1.acme.test" in r.detail and "not for localhost" in r.detail
    srv.close()

    leaf, key = _leaf(*pki["ca1"], days=(-30, -1))
    srv = Server(tmp_path, leaf, key)
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and r.verify_code == 10 and "expired" in r.detail
    srv.close()


def test_starttls_is_checked_the_same_way(tmp_path, pki):
    ca = load_ca(_ca_file(tmp_path, pki["ca1"][0]))
    leaf, key = _leaf(*pki["ca1"])
    srv = Server(tmp_path, leaf, key, starttls=True)
    r = check_tls(f"ldap://localhost:{srv.port}", start_tls=True, verify=True, ca=ca)
    assert r.ok and r.detail.startswith("StartTLS to localhost"), r.detail
    srv.close()
    leaf, key = _leaf(*pki["ca2"])
    srv = Server(tmp_path, leaf, key, starttls=True)
    r = check_tls(f"ldap://localhost:{srv.port}", start_tls=True, verify=True, ca=ca)
    assert not r.ok and r.verify_code == 7
    srv.close()
    srv = Server(tmp_path, leaf, key, starttls=True, refuse=True)
    r = check_tls(f"ldap://localhost:{srv.port}", start_tls=True, verify=True, ca=ca)
    assert not r.ok and "refused StartTLS" in r.detail
    srv.close()


def test_what_is_wrong_before_any_certificate(tmp_path, pki):
    ca = load_ca(_ca_file(tmp_path, pki["ca1"][0]))
    # nothing listens
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    r = check_tls(f"ldaps://127.0.0.1:{port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and "connection refused" in r.detail
    # a name that does not resolve
    r = check_tls("ldaps://dc1.acme.invalid:636", start_tls=False, verify=True, ca=ca)
    assert not r.ok and "does not resolve" in r.detail and "/etc/hosts" in r.detail
    # not TLS at all
    srv = Server(tmp_path, None, None, plain=True)
    r = check_tls(f"ldaps://127.0.0.1:{srv.port}", start_tls=False, verify=True, ca=ca)
    assert not r.ok and "TLS" in r.detail
    srv.close()
    # the CA file: missing, or not a certificate
    missing = load_ca(str(tmp_path / "nope.pem"))
    r = check_tls("ldaps://127.0.0.1:1", start_tls=False, verify=True, ca=missing)
    assert not r.ok and "does not exist" in r.detail and str(tmp_path) in r.detail
    junk = tmp_path / "junk.pem"
    junk.write_text("not a certificate")
    assert "holds no PEM certificate" in (load_ca(str(junk)).problem or "")


def test_not_verifying_is_said_plainly(tmp_path, pki):
    leaf, key = _leaf(*pki["other"])
    srv = Server(tmp_path, leaf, key)
    r = check_tls(f"ldaps://localhost:{srv.port}", start_tls=False, verify=False,
                  ca=load_ca(None))
    assert r.ok and "NOT verified" in r.detail and "Another CA" in r.detail
    srv.close()


def test_the_ca_file_does_not_depend_on_the_working_directory(tmp_path, monkeypatch):
    from gaia.core.config import ROOT

    monkeypatch.chdir(tmp_path)  # wherever the process runs
    # the form the guides use (relative to backend/, where make runs the API and the CLI)
    assert resolve_ca_file("../infra/auth/x.pem") == (ROOT / "infra/auth/x.pem").resolve()
    # relative to the repository root, when it exists there
    assert resolve_ca_file("config/gaia.yaml") == (ROOT / "config/gaia.yaml").resolve()
    assert resolve_ca_file(str(tmp_path / "a.pem")) == tmp_path / "a.pem"


def test_the_probe_stops_at_the_transport_and_keeps_the_ca_in_the_settings(tmp_path, pki):
    leaf, key = _leaf(*pki["ca2"])
    srv = Server(tmp_path, leaf, key)
    settings = LdapSettings(urls=[f"ldaps://localhost:{srv.port}"], bind_dn="cn=svc",
                            base_dn="dc=acme,dc=test", ca_pem=_pem(pki["ca1"][0]))
    binds = []
    d = LdapDirectory(settings, "pw", connect=lambda dn, pw: binds.append(dn),
                      transport=LdapDirectory(settings, "pw")._check_transport)
    checks = d.probe()
    assert [(c["name"], c["ok"]) for c in checks] == [("transport", False)]
    assert "the CA certificate in the settings" in checks[0]["detail"] and binds == []
    srv.close()


def test_connection_errors_read_as_causes():
    from ldap3.core.exceptions import LDAPSocketOpenError

    owner = LDAPSocketOpenError("(\"('socket ssl wrapping error: [SSL: CERTIFICATE_VERIFY_FAILED] "
                                "certificate verify failed: certificate signature failure "
                                "(_ssl.c:1000)',)\",)")
    text = describe_tls_error(owner)
    assert text.startswith("TLS: the directory's certificate is not signed by the CA Gaia trusts")
    assert "probe" in text and "_ssl.c" not in text
    assert "connection refused" in describe_tls_error(OSError("[Errno 111] Connection refused"))
